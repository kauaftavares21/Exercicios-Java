public class ParImpar {
    public static void main(String[] args){
        int numero1 = 8;
        int numero2 = 7;

        if(numero1 % 2 == 0){
            System.out.println("O número " + numero1 + " é par");
        } else {
            System.out.println("O número " + numero1 + " é ímpar");
        }

        if (numero2 % 2 == 0){
            System.out.println("O número " + numero2 + " é par");
        } else {
            System.out.println("O número " + numero2 + " é ímpar");
        }
    }
}
